  /** '400g' / '1根 120g' / '60g' → 数字克重；取不到返回 null */
  function parseGrams(text) {
    var s = String(text == null ? '' : text);
    var m = s.match(/(\d+(?:\.\d+)?)\s*g/i);
    if (m) return parseFloat(m[1]);
    m = s.match(/^(\d+(?:\.\d+)?)$/);
    return m ? parseFloat(m[1]) : null;
  }

