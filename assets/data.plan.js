  /** 一条记录的宏量（per 里出现非数字时按 0 算，绝不产生 NaN） */
  function itemMacros(it) {
    if (!it || !it.per) return { k: 0, p: 0, c: 0, f: 0 };
    var g = +it.g;
    if (!isFinite(g) || g <= 0) return { k: 0, p: 0, c: 0, f: 0 };
    var r = g / 100;
    function n(i) { var v = +it.per[i]; return isFinite(v) ? v * r : 0; }
    return { k: n(0), p: n(1), c: n(2), f: n(3) };
  }

  /** 一组记录的合计 */
  function sumItems(list) {
    var t = { k: 0, p: 0, c: 0, f: 0, n: 0 };
    (list || []).forEach(function (it) {
      if (!it || !it.per) return;
      var m = itemMacros(it);
      t.k += m.k; t.p += m.p; t.c += m.c; t.f += m.f; t.n++;
    });
    return t;
  }

  /**
   * 缺某个宏量时建议加什么、加多少克。
   * 直接用等价替换表的第一行换算（主食每份 40g 碳水 / 蛋白每份 25g / 脂肪每份 10g）。
   */
  function suggestFor(macro, needGram) {
    var g = null;
    for (var i = 0; i < SUBS.length; i++) if (SUBS[i].unit === macro) { g = SUBS[i]; break; }
    if (!g || !g.rows.length || needGram <= 0) return null;
    var row = g.rows[0];
    var per = parseGrams(row[1]);
    if (!per) return null;
    var idx = { c: 4, p: 3, f: 5 }[macro];
    var grams = Math.round(per * needGram / row[idx]);
    if (grams <= 0) return null;
    // 凑到好记的整数（5g 的倍数）
    grams = Math.max(5, Math.round(grams / 5) * 5);
    return { name: row[0], grams: grams, macro: macro };
  }

  /* ---- 实际 vs 目标：算差、判语气、给建议 ---- */
  var MACRO_DEF = [
    { key: 'k', i: 0, label: '热量', unit: 'kcal' },
    { key: 'p', i: 1, label: '蛋白', unit: 'g' },
    { key: 'c', i: 2, label: '碳水', unit: 'g' },
    { key: 'f', i: 3, label: '脂肪', unit: 'g' }
  ];
  var TOL = 0.10;          // ±10% 算达标，与全天达标线一致

  /**
   * actual / target 都可以是 {k,p,c,f} 或 [k,p,c,f]。
   * 返回 4 行：{ key, label, unit, actual, target, diff, pct, tone }
   * tone: 'ok'（±10% 内）/ 'over'（超了）/ 'under'（缺了）
   */
  function compareMacros(actual, target) {
    function pick(src, i) {
      if (Array.isArray(src)) return +src[i] || 0;
      return +src[MACRO_DEF[i].key] || 0;
    }
    return MACRO_DEF.map(function (m) {
      var a = pick(actual, m.i), t = pick(target, m.i);
      var diff = a - t;
      var pct = t ? diff / t : 0;
      return {
        key: m.key, label: m.label, unit: m.unit, i: m.i,
        actual: a, target: t, diff: diff, pct: pct,
        tone: Math.abs(pct) <= TOL ? 'ok' : (diff > 0 ? 'over' : 'under')
      };
    });
  }

  /**
   * 一句话建议：缺什么补什么（用等价替换表换算成具体克数），超了什么就提醒收一点。
   * 返回 [{ tone, text }]，永远不会是空数组。
   */
  function macroAdvice(rows) {
    var under = rows.filter(function (r) { return r.pct < -TOL; })
      .sort(function (a, b) { return a.pct - b.pct; });
    var over = rows.filter(function (r) { return r.pct > TOL; })
      .sort(function (a, b) { return b.pct - a.pct; });
    var out = [];
    var r0 = function (v) { return Math.round(v); };

    if (over.length) {
      var o = over[0];
      var tail = o.key === 'f' ? '，油、坚果、牛油果要收一点'
        : o.key === 'c' ? '，主食减一点' : '';
      out.push({
        tone: 'over',
        text: o.label + '超了 ' + r0(Math.abs(o.diff)) + o.unit +
          '（' + Math.round(Math.abs(o.pct) * 100) + '%）' + tail
      });
    }
    if (under.length) {
      var u = under[0];
      var s = u.key === 'k' ? null : suggestFor(u.key, -u.diff);
      out.push({
        tone: 'under',
        text: u.label + '还差 ' + r0(Math.abs(u.diff)) + u.unit +
          (s ? '，加 ' + s.grams + 'g ' + s.name + ' 差不多' : '')
      });
      var k = null, i;
      for (i = 0; i < rows.length; i++) if (rows[i].key === 'k') k = rows[i];
      if (u.key !== 'k' && k && k.pct < -TOL) {
        out.push({ tone: 'under', text: '热量还差 ' + r0(Math.abs(k.diff)) + ' kcal' });
      }
    }
    if (!out.length) out.push({ tone: 'ok', text: '宏量都在目标 ±10% 以内，刚好' });
    return out;
  }

